#!/usr/bin/env python3
"""Embeds ALLAN model files (.aln) into a Luau module as base64, so a Roblox place can carry them.

usage: python3 tools/embed_aln.py            (writes gallery/shared/AlnModels.luau)

Roblox scripts cannot read files, and Luau string literals holding raw bytes would grow up to
four times in escapes, so the models travel as base64 (4/3 of their size) in 96 character
lines and are decoded into buffers at run time.
"""
import base64
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# name -> (file, render scale r, one-line description)
MODELS = {
    "sdf_logo_256": ("assets/liquid/models/sdf_logo_256_N8_t8.aln", 0, "SDF logo with soft shadow, 256 x 256"),
    "ui_flat_256": ("assets/liquid/models/ui_flat_256_N8_t8.aln", 0, "flat UI art, 256 x 256"),
    "marble_64": ("assets/liquid/golden_marble64_r1.aln", 1, "marble, stored 32 x 32, rendered 2x larger"),
}

HEADER = '''--!strict
-- GENERATED by tools/embed_aln.py from assets/liquid/*.aln. Do not edit by hand.
--
-- ALLAN models (docs/LIQUID.md) carried as base64 so a Roblox place can hold them.
--   local Models = require(path.to.AlnModels)
--   local blob = Models.load("sdf_logo_256")   -- a buffer in the layout of src/Liquid.luau
--   local scale = Models.scale("marble_64")    -- the render scale r the model was trained for

local ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
local LUT: { [number]: number } = {}
for i = 1, 64 do
	LUT[string.byte(ALPHABET, i)] = i - 1
end

local function decode(parts: { string }): buffer
	local s = table.concat(parts)
	local n = #s
	local pad = 0
	if string.byte(s, n) == 61 then
		pad += 1
	end
	if string.byte(s, n - 1) == 61 then
		pad += 1
	end
	local out = buffer.create(n // 4 * 3 - pad)
	local o = 0
	for i = 1, n, 4 do
		local a, b, c, d = string.byte(s, i, i + 3)
		local v = LUT[a] * 262144 + LUT[b] * 4096 + (LUT[c] or 0) * 64 + (LUT[d] or 0)
		if o < buffer.len(out) then
			buffer.writeu8(out, o, v // 65536)
		end
		if o + 1 < buffer.len(out) then
			buffer.writeu8(out, o + 1, (v // 256) % 256)
		end
		if o + 2 < buffer.len(out) then
			buffer.writeu8(out, o + 2, v % 256)
		end
		o += 3
	end
	return out
end

local DATA: { [string]: { string } } = {
'''

FOOTER = '''}

local SCALE: { [string]: number } = {
%s}

local BYTES: { [string]: number } = {
%s}

local Models = {}

Models.names = { %s }

-- Decodes a model to a buffer (a new buffer on every call).
function Models.load(name: string): buffer
	local parts = DATA[name]
	assert(parts, "unknown ALLAN model " .. name)
	return decode(parts)
end

-- The render scale r (log2) the model expects, as in Liquid.prepare(model, tree, r).
function Models.scale(name: string): number
	return SCALE[name] or 0
end

-- Size in bytes of the encoded model.
function Models.bytes(name: string): number
	return assert(BYTES[name], "unknown ALLAN model " .. name)
end

return Models
'''


def main() -> None:
    out = [HEADER]
    scales = []
    sizes = []
    for name, (rel, scale, desc) in MODELS.items():
        raw = open(os.path.join(ROOT, rel), "rb").read()
        assert raw[:3] == b"ALN", rel
        b64 = base64.b64encode(raw).decode("ascii")
        out.append(f"\t-- {desc}: {len(raw)} bytes\n\t{name} = {{\n")
        for i in range(0, len(b64), 96):
            out.append(f'\t\t"{b64[i:i + 96]}",\n')
        out.append("\t},\n")
        scales.append(f"\t{name} = {scale},\n")
        sizes.append(f"\t{name} = {len(raw)},\n")
    names = ", ".join(f'"{n}"' for n in MODELS)
    out.append(FOOTER % ("".join(scales), "".join(sizes), names))
    path = os.path.join(ROOT, "gallery", "shared", "AlnModels.luau")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("".join(out))
    print(f"wrote {path} ({os.path.getsize(path)} bytes)")


if __name__ == "__main__":
    main()
